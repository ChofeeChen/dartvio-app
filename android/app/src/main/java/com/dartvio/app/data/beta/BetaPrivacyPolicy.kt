package com.dartvio.app.data.beta

/**
 * Beta 试用版的**隐私政策正文**。
 *
 * ## 为什么正文编译进包
 *
 * 对外发的包里，隐私政策必须是**打开就有**的，不能是一句「详见官网」——
 * 试用户很多是在地铁、地下室里第一次打开，让他联网去看一个链接，等于没告知。
 *
 * ## 写这份正文的两条纪律
 *
 * 1. **只写真实存在的东西**：每一项都要能对上一个具体的 `SharedPreferences` / 表的列。
 *    写「我们重视你的隐私」这种话没有意义，写「我们不读通讯录」才是承诺，而承诺是要被验的。
 * 2. **版本号与 [BetaConsent.POLICY_VERSION] 绑定**：改这里的内容 → 先 +1 那边的版本号，
 *    否则老用户不会被重新告知。
 */
object BetaPrivacyPolicy {

    const val VERSION = 1
    const val EFFECTIVE_DATE = "2026-09-26"

    /** 政策 ID，便于反馈时指认版本。 */
    val id: String get() = "v$VERSION · $EFFECTIVE_DATE"

    /**
     * 首屏摘要：**一屏内能读完**，也是大多数人实际会读的全部内容。
     * 下面的完整条款是给认真看的人和合规核对用的，不该挡在读摘要的路上。
     */
    val summary: List<String> = listOf(
        "你的对局数据只存在你自己的手机里，不上传。",
        "Beta 试用版会匿名上报「今天有个人打开了 App」，用于判断有多少人在用；它不含你的名字、昵称以外的任何身份信息，也不含你的成绩。",
        "不收集手机号、通讯录、相册、定位；没有广告 SDK，没有支付。",
        "不同意也不影响使用：可以把匿名统计关掉，功能一个不少。",
    )

    data class Section(val heading: String, val body: String)

    val sections: List<Section> = listOf(
        Section(
            "一、我们收集什么",
            "① 本机的一串随机编号（安装时生成，卸载重装就是新的）与一串由后端签发的随机号；" +
                "② 每天一次「当天有用过 App」的标记、App 版本号、Beta 渠道标记；" +
                "③ 若你填写了邀请码，则该码随上述记录一起上报，用于统计哪个渠道带来的试用者在用。",
        ),
        Section(
            "二、我们不收集什么",
            "不收集手机号、姓名、微信号、通讯录、相册、定位、通话记录；" +
                "不采集输入法内容；不接入任何广告 SDK、不读取已安装应用列表；" +
                "不使用广告标识符（OAID/GAID）。你的对局比分与训练数据不离开本机。",
        ),
        Section(
            "三、数据存在哪里、存多久",
            "匿名统计写入新加坡节点的后端，留存用于观察活跃趋势；" +
                "联机对战的房间数据与战绩写在同一套自建后端里，房间结束后只保留用于回看的记录。" +
                "本机数据保存在 App 私有目录，**卸载 App 即全部删除**。",
        ),
        Section(
            "四、你的选择",
            "① 首次启动可以选择不同意匿名统计，功能不受任何影响；" +
                "② 之后可在「我的」页查看本政策，并随时改变选择；" +
                "③ 卸载即删除本机全部本地数据；" +
                "④ 若希望我们删除与该随机编号相关的匿名记录，可通过下方微信联系我们处理。",
        ),
        Section(
            "五、第三方",
            "当前版本没有第三方数据分析服务、没有广告服务、没有支付功能。" +
                "若后续引入，会在新版本的这份文档里写明，并再次征得你的同意。",
        ),
        Section(
            "六、联系方式",
            "隐私相关问题可通过 Beta 群或微信二维码联系人处理；我们承诺在合理时间内答复。",
        ),
    )
}
