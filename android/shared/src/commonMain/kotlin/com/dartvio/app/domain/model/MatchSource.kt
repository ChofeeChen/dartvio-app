package com.dartvio.app.domain.model

/**
 * 一场对局是**怎么来的**（M5 T10）。
 *
 * 只有两个取值，但它们的待遇完全不同：
 *
 * - [LOCAL]：本机单机对局（含 AI 对战）。**唯一**计入 M9 统计、成就与排行榜的来源。
 * - [LAN]：联机（局域网）对局。**进历史列表**，但**不计入**统计 / 成就 / 排行榜。
 *
 * ## 为什么联机不算战绩
 *
 * 联机对局**无裁判**：比分由房主那台设备的服务端裁定，对手可以随时拔网线。
 * 更关键的是 T8 的弃权判负 —— 一旦把它计入胜率，「拔网线」就从一种故障变成了
 * 一种**提高数据的手段**，而这个漏洞没有任何事后校正的办法（没人能证明那 60 秒是真断线）。
 *
 * 因此联机局照样落库（打完能回看，这是用户资产），但统计口径显式排除它。
 * 排除逻辑集中在 [com.dartvio.app.data.local.MatchStatsFilter]，**不许**散落到各个查询里。
 *
 * ## 为什么用字符串存而不是枚举序号
 *
 * 落的是 [name]：序号一旦重排，老行读出来就变成了另一个来源。
 * 读取一律走 [fromKey] 的**宽容解析**（未知值回落 [LOCAL]）—— 历史行早于本列存在，
 * 迁移时统一补 `'LOCAL'`，两者语义相同，所以老用户的统计分母不会因为这次升级变化。
 */
enum class MatchSource {
    /** 单机（含 AI 对战）：计入统计。 */
    LOCAL,

    /** 联机：进历史，不计入统计。 */
    LAN,
    ;

    companion object {
        /** 宽容解析：无法识别的来源一律按 [LOCAL] 处理（老行与未知新值都不该被静默剔除）。 */
        fun fromKey(key: String?): MatchSource =
            entries.firstOrNull { it.name == key } ?: LOCAL
    }
}
